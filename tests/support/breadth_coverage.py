"""Which rules have a breadth file, and the generated coverage table in docs/TESTING.md.

`render_coverage_block` is checked against the doc by `tests/meta/test_breadth_catalog_doc.py`.
"""
from __future__ import annotations

from collections import Counter

from src.pkg.rules.register_rules import module_rule_runner, rule_runner, symbol_rule_runner
from tests.support.breadth_catalog import BREADTH_ROOT, all_breadth_files, parse_breadth_cases

PENDING_FILE = BREADTH_ROOT / "PENDING_RULES.txt"
BEGIN_MARKER = "<!-- BEGIN BREADTH COVERAGE (generated by tests/meta/test_breadth_catalog_doc.py) -->"
END_MARKER = "<!-- END BREADTH COVERAGE -->"


def registered_categories() -> dict[str, str]:
    """rule code -> category folder (`src/pkg/rules/<category>/...`)."""
    registered: dict[str, str] = {}
    for runner in (rule_runner, symbol_rule_runner, module_rule_runner):
        for rule in runner._rules:
            registered[rule.code] = type(rule).__module__.split(".")[3]
    return registered


def pending_rules() -> set[str]:
    return {line.strip() for line in PENDING_FILE.read_text(encoding="utf-8").splitlines() if line.strip()}


def render_coverage_block() -> str:
    """The marked block: a per-category summary, then one row per rule that has a breadth file."""
    registered = registered_categories()
    with_breadth = {p.stem: parse_breadth_cases(p) for p in all_breadth_files()}
    totals: Counter = Counter(registered.values())
    covered: Counter = Counter(registered[code] for code in with_breadth if code in registered)

    lines = [BEGIN_MARKER, "", f"{len(with_breadth)} of {len(registered)} rules have a breadth file.", "",
             "| Category | Rules | With breadth cases | Pending |", "|---|---|---|---|"]
    for category in sorted(totals):
        lines.append(f"| `{category}` | {totals[category]} | {covered[category]} | {totals[category] - covered[category]} |")
    lines += ["", "| Rule | Category | `reports` | `clean` | `gap` | Pairs |", "|---|---|---|---|---|---|"]
    for code in sorted(with_breadth, key=lambda c: (registered.get(c, ""), c)):
        breadth_cases = with_breadth[code]
        kinds = Counter(c.kind for c in breadth_cases)
        pairs = len({c.pair for c in breadth_cases if c.pair})
        lines.append(f"| `{code}` | `{registered.get(code, '?')}` | {kinds['reports']} | {kinds['clean']} | {kinds['gap']} | {pairs} |")
    lines += ["", END_MARKER]
    return "\n".join(lines)
